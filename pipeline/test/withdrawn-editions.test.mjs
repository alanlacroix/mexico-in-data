import assert from 'node:assert/strict';
import fs from 'node:fs';
import { publicationPlan } from '../publication-plan.mjs';
import { readWithdrawals } from '../lib/withdrawn-editions.mjs';
const edition=JSON.parse(fs.readFileSync(new URL('../../data/editions/2026-11-07.json',import.meta.url)));
const withdrawals=readWithdrawals();
const row={editorialDate:'2026-11-12',slot:'morning',state:'published',artifactHash:'755c0448a53f639b923d3b661275d391383c96a5f52d97d4c4b10caa96147290'};
const input={event:'schedule',date:'2026-11-12',attempts:{attempts:[row]},edition,withdrawals};
const plan=publicationPlan(input);
assert.equal(plan.run,false);assert.equal(plan.held,true);assert.equal(plan.verify,true);
for(const event of ['schedule','workflow_dispatch','workflow_run']) assert.equal(publicationPlan({...input,event,retry:true}).held,true);
assert.throws(()=>publicationPlan({...input,withdrawals:undefined}),/does not match/);
assert.throws(()=>publicationPlan({...input,edition:{...edition,artifactHash:'a'.repeat(64)}}),/last-good/);
assert.throws(()=>publicationPlan({...input,edition:{...edition,editorialDate:row.editorialDate,artifactHash:row.artifactHash}}),/last-good/);
assert.throws(()=>publicationPlan({...input,withdrawals:{schemaVersion:1,withdrawals:[...withdrawals.withdrawals,...withdrawals.withdrawals]}}),/Ambiguous/);
assert.throws(()=>publicationPlan({...input,withdrawals:{schemaVersion:1,withdrawals:[{...withdrawals.withdrawals[0],lastGoodHash:'invalid'}]}}),/Invalid/);
assert.throws(()=>publicationPlan({...input,attempts:{attempts:[row,row]}}),/Ambiguous/);
const next=publicationPlan({...input,date:'2026-11-13'});assert.equal(next.run,true);assert.equal(next.held,undefined);
const normal=publicationPlan({...input,edition:{editorialDate:row.editorialDate,artifactHash:'new'},attempts:{attempts:[{...row,artifactHash:'new'}]}});assert.equal(normal.verify,true);assert.equal(normal.held,undefined);
const yml=fs.readFileSync(new URL('../../.github/workflows/happening.yml',import.meta.url),'utf8');
const held=yml.split('      - name: Verify retained edition during editorial hold')[1].split('      - name:')[0];
assert.match(held,/verify-production/);assert.doesNotMatch(held,/continue-on-error|claim-deployment|git add/);
const retry=yml.split('      - name: Retry deployment once')[1];assert.match(retry,/steps.plan.outputs.held != 'true'/);
console.log('withdrawn editions: ok');
